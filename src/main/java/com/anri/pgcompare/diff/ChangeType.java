package com.anri.pgcompare.diff;

/**
 * Тип изменения объекта; в JSON-отчёт попадает как строка с этим именем. Направление
 * фиксировано: источник — мигрируемая сторона, цель — желаемое состояние.
 */
public enum ChangeType {
    /** Объект есть только в цели — его нужно создать; обычно даёт severity {@code NON_BREAKING}. */
    ADDED,
    /** Объект есть только в источнике — его нужно удалить; обычно даёт severity {@code BREAKING}. */
    REMOVED,
    /** Объект есть с обеих сторон, но его определение расходится. */
    MODIFIED
}
