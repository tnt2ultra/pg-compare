package com.anri.pgcompare.diff;

/**
 * Тип объекта, к которому относится запись отчёта; в JSON-отчёт попадает как строка с этим
 * именем. Вместе с {@link ChangeType} определяет {@link Severity} записи.
 */
public enum ObjectType {
    /** Таблица целиком; имя объекта в записи — имя таблицы. */
    TABLE,
    /** Колонка; имя объекта в записи — «таблица.колонка». */
    COLUMN,
    /** Констрейнт; имя объекта в записи — «таблица.имя_констрейнта». */
    CONSTRAINT,
    /** Отдельный индекс; имя объекта в записи — «таблица.имя_индекса». */
    INDEX,
    /** Sequence; сравнивается целиком по набору параметров. */
    SEQUENCE,
    /** Комментарий таблицы или колонки; единственный тип, который всегда идёт как {@code INFO}. */
    COMMENT
}
