package com.anri.pgcompare.diff;

/**
 * Насколько изменение опасно для приложений, работающих со схемой; в JSON-отчёт попадает
 * как строка с этим именем. Назначается {@link SeverityClassifier}.
 */
public enum Severity {
    /** Ломает работу приложений: любое удаление и любое изменение колонки. Требует ревью. */
    BREAKING,
    /** Не ломает существующую работу: добавление объекта либо переопределение на месте. */
    NON_BREAKING,
    /** Справочная запись — на работу приложения не влияет (комментарии). */
    INFO
}
