package com.anri.pgcompare.model;

/**
 * Вид констрейнта. Определяет, какие атрибуты определения осмысленны (например, опорная
 * таблица заполнена только у {@link #FOREIGN_KEY}) и какой DDL способен его воссоздать.
 */
public enum ConstraintType {
    /** Первичный ключ ({@code p}): уникальность и NOT NULL, опора для внешних ключей. */
    PRIMARY_KEY,
    /** Внешний ключ ({@code f}): ссылается на колонки опорной таблицы. */
    FOREIGN_KEY,
    /** Уникальность ({@code u}): сопровождающий индекс в снимке не дублируется. */
    UNIQUE,
    /** Проверка условия ({@code c}): строка обязана удовлетворять булевому предикату. */
    CHECK,
    /** Исключение ({@code x}): строки не должны пересекаться по заданному оператору. */
    EXCLUSION
}
